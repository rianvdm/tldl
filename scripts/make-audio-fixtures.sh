#!/usr/bin/env bash
# Generates test/fixtures/audio.ts: small base64-encoded audio fixtures for the
# MP4 reader and chunking tests (the Workers test pool has no filesystem).
#
# Regenerate with:  bash scripts/make-audio-fixtures.sh
# Requires ffmpeg and ffprobe on PATH (macOS: brew install ffmpeg).
set -euo pipefail

export PATH="/opt/homebrew/bin:$PATH"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/test/fixtures/audio.ts"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

SRC=(-f lavfi -i "sine=frequency=440:duration=5")
OUTFMT=(-ac 1 -ar 44100)
FF=(ffmpeg -v error -y)

"${FF[@]}" "${SRC[@]}" "${OUTFMT[@]}" -c:a aac -b:a 64k -movflags +faststart "$TMP/moov-first.m4a"
"${FF[@]}" "${SRC[@]}" "${OUTFMT[@]}" -c:a aac -b:a 64k "$TMP/moov-last.m4a"

cat > "$TMP/chapters.ffmeta" <<'META'
;FFMETADATA1
title=Fixture
[CHAPTER]
TIMEBASE=1/1000
START=0
END=2000
title=One
[CHAPTER]
TIMEBASE=1/1000
START=2000
END=5000
title=Two
META
"${FF[@]}" "${SRC[@]}" -i "$TMP/chapters.ffmeta" "${OUTFMT[@]}" -map 0:a -map_metadata 1 -map_chapters 1 \
    -c:a aac -b:a 64k -movflags +faststart "$TMP/chapters.m4a"

# The chapters fixture must carry a second, non-audio track (a QuickTime text track).
STREAMS="$(ffprobe -v error -show_entries stream=codec_type -of csv=p=0 "$TMP/chapters.m4a" | wc -l | tr -d ' ')"
if [ "$STREAMS" -lt 2 ]; then
    echo "ERROR: ffmpeg did not produce a chapter text track in chapters.m4a ($STREAMS stream(s))" >&2
    exit 1
fi

"${FF[@]}" "${SRC[@]}" "${OUTFMT[@]}" -c:a aac -b:a 64k -movflags frag_keyframe+empty_moov "$TMP/fragmented.m4a"
"${FF[@]}" "${SRC[@]}" "${OUTFMT[@]}" -c:a alac "$TMP/alac.m4a"
"${FF[@]}" "${SRC[@]}" "${OUTFMT[@]}" -c:a aac -b:a 64k -f adts "$TMP/aac.aac"
"${FF[@]}" "${SRC[@]}" "${OUTFMT[@]}" -c:a aac -b:a 64k -write_id3v2 1 -metadata title=fixture -f adts "$TMP/aac-id3.aac"

emit() { # name file
    printf 'export const %s =\n    "%s";\n\n' "$1" "$(base64 < "$2" | tr -d '\n')"
}

{
    echo '// Generated by scripts/make-audio-fixtures.sh. Do not edit by hand.'
    echo '// Each fixture is a 5 second, mono, 44.1 kHz 440 Hz tone, base64 encoded.'
    echo
    emit MOOV_FIRST_M4A "$TMP/moov-first.m4a"
    emit MOOV_LAST_M4A "$TMP/moov-last.m4a"
    emit CHAPTERS_M4A "$TMP/chapters.m4a"
    emit FRAGMENTED_M4A "$TMP/fragmented.m4a"
    emit ALAC_M4A "$TMP/alac.m4a"
    emit ADTS_AAC "$TMP/aac.aac"
    emit ADTS_AAC_ID3 "$TMP/aac-id3.aac"
    cat <<'TS'
/** Decode a base64 fixture into bytes. */
export function fixtureBytes(b64: string): Uint8Array {
    const bin = atob(b64);
    const out = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
    return out;
}
TS
} > "$OUT"

echo "Wrote $OUT ($(wc -c < "$OUT") bytes)"
echo "chapters.m4a streams:"
ffprobe -v error -show_entries stream=index,codec_type,codec_tag_string -of csv "$TMP/chapters.m4a"
